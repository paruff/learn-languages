// Offline support (spec Q7, JTBD-1 "10 minutes on the bus, no signal").
// Runtime caching only — no precache manifest: a page works offline once it
// has been visited online. ponytail: no precache; add a build-time manifest
// if learners need pages offline they've never opened.
const CACHE = 'acquira-v1';

self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;

  // Pages: network-first so content updates land immediately; cache is the fallback.
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request).then((cached) => cached || Response.error()))
    );
    return;
  }

  // Assets (hashed /_astro/ bundles, fonts, images): cache-first.
  // ponytail: unhashed files (/vocab-images/, /fonts/) replaced at the same
  // path stay stale for returning visitors; bump CACHE when that happens.
  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
    )
  );
});
