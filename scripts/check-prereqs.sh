#!/usr/bin/env bash
# Verifies (and with --install, fixes) what `pre-commit run --all-files` needs.
# Never builds from source: brew bottles only (--force-bottle), Docker for semgrep.
set -uo pipefail
cd "$(dirname "$0")/.."

install=0; [ "${1:-}" = "--install" ] && install=1
missing=0

need() { # need <command> <brew formula>
  command -v "$1" >/dev/null 2>&1 && { echo "ok       $1"; return; }
  if [ "$install" = 1 ] && command -v brew >/dev/null 2>&1; then
    echo "install  $1 (brew bottle)"
    brew install --force-bottle "$2" || { echo "FAILED   $1: no bottle? install a prebuilt binary instead"; missing=1; }
  else
    echo "MISSING  $1 (brew install --force-bottle $2, or run: npm run setup:checks)"; missing=1
  fi
}

need pre-commit pre-commit
need gitleaks gitleaks
need trivy trivy

# npm tooling (eslint, prettier, tsc, vitest, lefthook)
if [ -x node_modules/.bin/eslint ] && [ -x node_modules/.bin/vitest ]; then
  echo "ok       npm dependencies"
elif [ "$install" = 1 ]; then
  echo "install  npm dependencies"; npm ci || missing=1
else
  echo "MISSING  npm dependencies (npm ci, or run: npm run setup:checks)"; missing=1
fi

# lefthook owns .git/hooks; pre-commit must never install itself there (AGENTS.md §11)
if grep -q "pre-commit.com\|File generated by pre-commit" .git/hooks/pre-commit 2>/dev/null; then
  echo "WARNING  pre-commit overwrote lefthook's hook: run 'npx lefthook install'"; missing=1
fi

# Docker (colima) is needed only for the manual-stage semgrep hook
if docker info >/dev/null 2>&1; then
  echo "ok       docker"
elif [ "$install" = 1 ] && command -v colima >/dev/null 2>&1; then
  echo "start    colima"; colima start && echo "ok       docker" || { echo "FAILED   colima start"; missing=1; }
else
  echo "NOTE     docker not running (only semgrep needs it): colima start"
fi

[ "$missing" = 0 ] && echo "Ready: pre-commit run --all-files" || { echo "Not ready."; exit 1; }
